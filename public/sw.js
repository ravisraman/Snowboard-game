/**
 * Offline cache.
 *
 * The hosted build is a folder rather than one file, which means it needs a
 * network the first time — so this puts back what the single-file build gave
 * away.
 *
 * ## Why this is not simply cache-first
 *
 * It was, and that was a bug that took the deployed site down.
 *
 * Vite gives every build content-hashed asset names, and `index.html` is the
 * one file that names them. Precaching `index.html` and then serving it
 * cache-first pins a returning visitor to whichever build they happened to see
 * first: the browser hands them last week's HTML, which asks for
 * `index-BG8hQ20v.js`, which the next deploy deleted from the server. Best
 * case they are stuck on an old build forever; worst case — and it is the
 * common case, once the browser's own HTTP cache lets go of the file — the
 * page comes up blank. Nothing about it self-heals, because a cache-first
 * worker never fetches the HTML that would tell it it is out of date.
 *
 * So the two kinds of file are treated as what they are:
 *
 * - **The HTML is network-first.** It is small, it changes every deploy, and
 *   it is the only thing that knows the current asset names. The cached copy
 *   is the *offline fallback*, not the answer.
 * - **Hashed assets are cache-first.** A content hash means a URL can only
 *   ever return one body, so caching it forever is not a risk — it is the
 *   whole point of the hash.
 *
 * `CACHE` carries a version, and `activate` deletes every cache that is not
 * it. Bumping that string is what clears the old scheme off machines that have
 * already been broken by it.
 *
 * Hand-written rather than generated by a plugin: there are four files in the
 * shell, and a build-time asset manifest would be more machinery than the
 * problem is worth.
 */

const CACHE = 'alpine-carve-v2';

// The shell, kept so the game still opens with no network at all. `index.html`
// is in here as a fallback only — see the note above on why it is never the
// preferred answer while there is a network.
const SHELL = ['./', './index.html', './manifest.webmanifest', './icon.svg'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  // Drop every cache that is not this version — including `alpine-carve-v1`,
  // which is the one holding the stale `index.html` — then take over open
  // pages immediately.
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

/** Worth keeping: a real, complete, same-origin response. */
function cacheable(response) {
  return response && response.status === 200 && response.type === 'basic';
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  // Same-origin only: there is nothing else to cache, and proxying anything
  // else would be a surprise.
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Navigations, and anything else asking for HTML: go to the network, and
  // fall back to the cache only when there is not one.
  const wantsHTML =
    request.mode === 'navigate' || (request.headers.get('accept') || '').includes('text/html');

  if (wantsHTML) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (cacheable(response)) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => caches.match(request).then((hit) => hit || caches.match('./index.html')))
    );
    return;
  }

  // Everything else — hashed JS and CSS, the icon, the manifest — is immutable
  // at its URL, so a cache hit is always the right answer.
  event.respondWith(
    caches.match(request).then((hit) => {
      if (hit) return hit;
      return fetch(request).then((response) => {
        if (!cacheable(response)) return response;
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(request, copy));
        return response;
      });
    })
  );
});
